        "                    drive_mp3 = drive_model_dir / final_mp3_name\n",
        "                    \n",
        "                    if SKIP_EXISTING and drive_mp3.exists() and drive_mp3.stat().st_size > 1000:\n",
        "                        print(f\"  ⏩ [SKIP] OpenVoice {spk}_{lang} (Sudah ada di Drive)\", flush=True)\n",
        "                        continue\n",
        "                        \n",
        "                    print(f\"  ⚡ [GENERATE] OpenVoice {spk}_{lang}...\", flush=True)\n",
        "                    tmp_wav = out_dir / f\"tmp_{spk}_{lang}.wav\"\n",
        "                    final_wav = out_dir / f\"{spk}_{lang}.wav\"\n",
        "                    final_mp3 = out_dir / final_mp3_name\n",
        "                    \n",
        "                    base_tts.tts_to_file(text, speaker_id, str(tmp_wav), speed=1.0)\n",
        "                    converter.convert(str(tmp_wav), source_se, target, str(final_wav), message=\"@Research\")\n",
        "                    mp3_from_wav(final_wav, final_mp3)\n",
        "                    sync_single_file(final_mp3, \"OpenVoice\")\n",
        "                    if tmp_wav.exists(): tmp_wav.unlink()\n",
        "            except Exception as e:\n",
        "                print(f\"  ❌ [ERROR] OpenVoice {spk}: {e}\", flush=True)\n",
        "            finally:\n",
        "                free_memory()\n",
        "                \n",
        "        del converter, base_tts, source_se\n",
        "        free_memory()\n",
        "\n",
        "    # ────────────────────────────────────────────────────────────\n",
        "    # 3. RUN VOXCPM BATCH (IF REQUESTED)\n",
        "    # ────────────────────────────────────────────────────────────\n",
        "    if \"VoxCPM\" in MODELS_TO_RUN:\n",
        "        print(\"\\n==================== MODEL: VoxCPM ====================\", flush=True)\n",
        "        try:\n",
        "            from voxcpm import VoxCPM\n",
        "            import soundfile as sf\n",
        "            model = VoxCPM.from_pretrained(\"OpenBMB/VoxCPM-SF\")\n",
        "            out_dir = OUT / \"VoxCPM\"\n",
        "            out_dir.mkdir(parents=True, exist_ok=True)\n",
        "            drive_model_dir = DRIVE_OUT / \"VoxCPM\"\n",
        "            drive_model_dir.mkdir(parents=True, exist_ok=True)\n",
        "            \n",
        "            for spk in selected_speakers:\n",
        "                ref_id = REF_ROOT / f\"Suaraindo_{spk}.wav\"\n",
        "                ref_en = REF_ROOT / f\"Suaraeng_{spk}.wav\"\n",
        "                if not ref_id.exists(): ref_id = list(REF_ROOT.glob(f\"*{spk}*.wav\"))[0]\n",
        "                if not ref_en.exists(): ref_en = ref_id\n",
        "                \n",
        "                for lang, text, ref in ((\"id\", TEXTS[\"id\"], ref_id), (\"en\", TEXTS[\"en\"], ref_en)):\n",
