        "    # ────────────────────────────────────────────────────────────\n",
        "    # 1. RUN F5-TTS BATCH\n",
        "    # ────────────────────────────────────────────────────────────\n",
        "    if \"F5-TTS\" in MODELS_TO_RUN:\n",
        "        print(\"\\n==================== MODEL: F5-TTS ====================\", flush=True)\n",
        "        install(\"f5-tts\")\n",
        "        out_dir = OUT / \"F5-TTS\"\n",
        "        out_dir.mkdir(parents=True, exist_ok=True)\n",
        "        drive_model_dir = DRIVE_OUT / \"F5-TTS\"\n",
        "        drive_model_dir.mkdir(parents=True, exist_ok=True)\n",
        "        \n",
        "        for spk in selected_speakers:\n",
        "            ref_id = REF_ROOT / f\"Suaraindo_{spk}.wav\"\n",
        "            ref_en = REF_ROOT / f\"Suaraeng_{spk}.wav\"\n",
        "            if not ref_id.exists(): ref_id = list(REF_ROOT.glob(f\"*{spk}*.wav\"))[0]\n",
        "            if not ref_en.exists(): ref_en = ref_id\n",
        "            \n",
        "            for lang, text, ref in ((\"id\", TEXTS[\"id\"], ref_id), (\"en\", TEXTS[\"en\"], ref_en)):\n",
        "                final_mp3_name = f\"{spk}_{lang}.mp3\"\n",
        "                drive_mp3 = drive_model_dir / final_mp3_name\n",
        "                \n",
        "                if SKIP_EXISTING and drive_mp3.exists() and drive_mp3.stat().st_size > 1000:\n",
        "                    print(f\"  ⏩ [SKIP] F5-TTS {spk}_{lang} (Sudah ada di Drive)\", flush=True)\n",
        "                    continue\n",
        "                    \n",
        "                print(f\"  ⚡ [GENERATE] F5-TTS {spk}_{lang}...\", flush=True)\n",
        "                try:\n",
        "                    wav_out = out_dir / f\"{spk}_{lang}.wav\"\n",
        "                    mp3_out = out_dir / final_mp3_name\n",
        "                    run(\"f5-tts_infer-cli\", \"--model\", \"F5TTS_v1_Base\", \"--ref_audio\", str(ref), \"--ref_text\", \"\", \"--gen_text\", text, \"--output_dir\", str(out_dir), \"--output_file\", f\"{spk}_{lang}.wav\")\n",
        "                    mp3_from_wav(wav_out, mp3_out)\n",
        "                    sync_single_file(mp3_out, \"F5-TTS\")\n",
        "                except Exception as e:\n",
        "                    print(f\"  ❌ [ERROR] F5-TTS {spk}_{lang}: {e}\", flush=True)\n",
        "                finally:\n",
        "                    free_memory()\n",
        "        free_memory()\n",
