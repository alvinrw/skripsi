        "                        mp3_out = out_dir / final_mp3_name\n",
        "                        sf.write(str(wav_out), wav, model.tts_model.sample_rate)\n",
        "                        mp3_from_wav(wav_out, mp3_out)\n",
        "                        sync_single_file(mp3_out, \"VoxCPM\")\n",
        "                    except Exception as e:\n",
        "                        print(f\"  ❌ [ERROR] VoxCPM {spk}_{lang}: {e}\", flush=True)\n",
        "                    finally:\n",
        "                        free_memory()\n",
        "            del model\n",
        "            free_memory()\n",
        "        except Exception as e:\n",
        "            print(f\"  ❌ [ERROR] Gagal inisialisasi VoxCPM: {e}\", flush=True)\n",
