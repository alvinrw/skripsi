        "# ============================================================\n",
        "\n",
        "def run_batch_generation():\n",
        "    all_speakers = scan_speakers()\n",
        "    if not all_speakers:\n",
        "        print(\"❌ Tidak ada speaker WAV yang ditemukan di reference data.\")\n",
